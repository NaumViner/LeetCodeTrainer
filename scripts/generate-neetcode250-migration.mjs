import { readFile, writeFile } from "node:fs/promises";
import { topicMetadata } from "./catalog-topic-metadata.mjs";
const read = async (file) => JSON.parse(await readFile(file, "utf8"));
const catalog = await read("data/neetcode-250.json");
const original = await read("data/problems.json");
const followUps = await read("data/neetcode250-follow-ups.json");
const old = new Set(original.problems.map((p) => p.slug));
const extra = catalog.problems.filter((p) => !old.has(p.slug));
if (
  catalog.problems.length !== 250 ||
  extra.length !== 100 ||
  new Set(catalog.problems.map((p) => p.slug)).size !== 250 ||
  new Set(catalog.problems.map((p) => p.externalId)).size !== 250 ||
  Object.keys(followUps).length !== 100 ||
  extra.some((p) => !followUps[p.slug] || !topicMetadata[p.primaryTopic])
)
  throw new Error("Catalog or follow-up coverage mismatch");
for (const p of original.problems) {
  if (
    JSON.stringify(catalog.problems.find((x) => x.slug === p.slug)) !==
    JSON.stringify(p)
  )
    throw new Error("Historical metadata changed: " + p.slug);
}
const str = (s) => "'" + s.replaceAll("'", "''") + "'";
const arr = (a) => "array[" + a.map(str).join(", ") + "]::text[]";
const rows = extra.map((p) => {
  const meta = topicMetadata[p.primaryTopic];
  return `('leetcode', ${str(p.externalId)}, ${str(p.slug)}, ${str(p.title)}, ${str(p.difficulty)}, ${str("https://leetcode.com/problems/" + p.slug + "/")}, (select id from public.topics where slug=${str(p.primaryTopic)}), ${arr(meta.tags)}, ${arr(meta.signals)}, ${p.difficulty === "easy" ? 20 : p.difficulty === "medium" ? 35 : 50}, ${str(p.difficulty === "easy" ? "foundation" : p.difficulty === "medium" ? "independent" : "interview")}, ${p.premium}, ${catalog.problems.findIndex((x) => x.slug === p.slug) + 1}, true, 1, 'first_party')`;
});
const sql = `-- Generated by scripts/generate-neetcode250-migration.mjs.
-- Metadata identifiers from the official NeetCode 250 snapshot, 2026-09-23.
-- Original interview content lives in the server registry. Preserve all 150
-- previous problem IDs, collection memberships, content versions and snapshots.

insert into public.problems (source,external_id,slug,title,difficulty,external_url,primary_topic_id,pattern_tags,recognition_signals,estimated_minutes,curriculum_level,premium,dataset_order,interview_ready,interview_content_version,interview_content_provenance)
values
${rows.join(",\n")};

insert into public.problem_prerequisite_topics(problem_id,topic_id)
select p.id,t.id from (values
${extra.flatMap((p) => topicMetadata[p.primaryTopic].prerequisites.map((t) => `(${str(p.slug)},${str(t)})`)).join(",\n")}
) as authored(slug,topic_slug)
join public.problems p on p.source='leetcode' and p.slug=authored.slug
join public.topics t on t.slug=authored.topic_slug;

insert into public.problem_collections(slug,name,version,expected_problem_count,expected_primary_topic_count)
values ('neetcode-250','NeetCode 250',1,250,18);

insert into public.problem_collection_memberships(collection_id,problem_id,primary_topic_id,ordinal)
select c.id,p.id,p.primary_topic_id,authored.ordinal
from (values
${catalog.problems.map((p, i) => `(${str(p.slug)},${i + 1})`).join(",\n")}
) as authored(slug,ordinal)
join public.problems p on p.source='leetcode' and p.slug=authored.slug
cross join public.problem_collections c where c.slug='neetcode-250' and c.version=1;

insert into public.approved_interview_follow_ups(problem_id,content_version,prompt)
select p.id,1,authored.prompt from (values
${extra.map((p) => `(${str(p.slug)},${str(followUps[p.slug])})`).join(",\n")}
) as authored(slug,prompt)
join public.problems p on p.source='leetcode' and p.slug=authored.slug;

-- Switch the actual start gate as well as the UI selection source. Keep all
-- authentication, ready-content, difficulty and single-active-session checks.
do $$
declare definition text;
begin
  definition := pg_get_functiondef('public.start_mock_interview_v2(uuid,integer,text,uuid,text[],uuid,integer,jsonb,text,text,text)'::regprocedure);
  if strpos(definition, 'collection.slug = ''neetcode-150''') = 0
    or strpos(definition, '''candidateProblemCount'')::integer not between 1 and 150') = 0 then
    raise exception 'Unexpected interview start function; inspect before upgrading';
  end if;
  definition := replace(definition, 'collection.slug = ''neetcode-150''', 'collection.slug = ''neetcode-250''');
  definition := replace(definition, '''candidateProblemCount'')::integer not between 1 and 150', '''candidateProblemCount'')::integer not between 1 and 250');
  execute definition;
end;
$$;

do $$
declare problem_count integer; topic_count integer; followup_count integer;
begin
  select count(*),count(distinct m.primary_topic_id),count(f.problem_id)
  into problem_count,topic_count,followup_count
  from public.problem_collection_memberships m
  join public.problem_collections c on c.id=m.collection_id
  join public.problems p on p.id=m.problem_id and p.active and p.interview_ready
  left join public.approved_interview_follow_ups f on f.problem_id=p.id
    and f.content_version=p.interview_content_version and f.active
  where c.slug='neetcode-250' and c.version=1;
  if problem_count<>250 or topic_count<>18 or followup_count<>250 then
    raise exception 'Incomplete NeetCode 250 inventory: % problems, % topics, % follow-ups',problem_count,topic_count,followup_count;
  end if;
  if (select count(*) from public.problem_collection_memberships m join public.problem_collections c on c.id=m.collection_id where c.slug='neetcode-150' and c.version=1)<>150 then
    raise exception 'Historical NeetCode 150 membership changed';
  end if;
end;
$$;
`;
await writeFile(
  "supabase/migrations/20260923120000_complete_neetcode250_inventory.sql",
  sql,
);
console.log(
  "Generated NeetCode 250 migration: 100 new problems, 250 memberships, 100 follow-ups.",
);
